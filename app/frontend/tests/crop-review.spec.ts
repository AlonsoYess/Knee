import { test, expect, type Page } from '@playwright/test'

async function startReview(page: Page) {
  await page.goto('/acceso')
  await page.getByRole('button', { name: 'Completar datos de ejemplo' }).click()
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await page.getByRole('button', { name: 'Nueva evaluación', exact: true }).click()
  await page.getByRole('button', { name: 'Completar ejemplo', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await page.getByRole('button', { name: 'Seleccionar imagen A', exact: true }).click()
  await page.locator('#radiograph-confirmation').check()
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Revisión del recorte', exact: true })).toBeVisible()
  await expect(page.locator('#crop-reviewed')).toBeEnabled()
}

async function acceptSaved(page: Page) {
  await page.locator('#crop-reviewed').check()
  await page.getByRole('button', { name: 'Aceptar recorte de ejemplo', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await expect(page.locator('tbody tr').filter({ hasText: 'DEMO-008' })).toContainText('Recorte aceptado (demo)')
  await page.getByRole('button', { name: 'Ver revisión DEMO-008', exact: true }).click()
}

test('explicit acceptance, previews and resume stay bound to the same synthetic source', async ({ page, baseURL }) => {
  const localOrigin = new URL(baseURL!).origin
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!request.url().startsWith(`${localOrigin}/`) && !request.url().startsWith('data:')) external.push(request.url()) })
  await startReview(page)
  await page.getByRole('button', { name: 'Aceptar recorte de ejemplo', exact: true }).click()
  await expect(page.locator('#crop-reviewed-error')).toBeVisible()
  await page.getByRole('button', { name: 'Ampliar original', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Imagen original ampliada' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Ampliar original', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Ampliar recorte', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Recorte ampliado' })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.screenshot({ path: 'test-results/crop-review-desktop.png', fullPage: true })
  await page.locator('#crop-reviewed').check()
  await page.getByRole('button', { name: 'Aceptar recorte de ejemplo', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Guardar y ver resumen', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Guardar y ver resumen', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Resumen del caso', exact: true })).toBeVisible()
  await expect(page.locator('#summary-prediction-block')).toContainText('Modelos sin conectar')
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(8)
  await page.getByRole('button', { name: 'Ver resumen DEMO-008', exact: true }).click()
  await page.getByRole('link', { name: 'Revisar recorte', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reabrir revisión', exact: true })).toBeVisible()
  await expect(page.locator('#crop-reviewed')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Calcular resultado' })).toHaveCount(0)
  expect(errors).toEqual([])
  expect(external).toEqual([])
})

test('rejection requires a reason and reopening requires an explicit decision', async ({ page }) => {
  await startReview(page)
  await page.getByRole('button', { name: 'Rechazar recorte de ejemplo', exact: true }).click()
  await expect(page.locator('#crop-reason-error')).toBeVisible()
  await page.locator('#crop-reason').selectOption('incomplete-example')
  await page.getByRole('button', { name: 'Rechazar recorte de ejemplo', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Guardar y ver resumen', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Guardar y salir', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await expect(page.locator('tbody tr').filter({ hasText: 'DEMO-008' })).toContainText('Recorte rechazado (demo)')
  await page.getByRole('button', { name: 'Ver revisión DEMO-008', exact: true }).click()
  await expect(page.locator('.crop-rejected-reason')).toContainText('Región incompleta')
  await page.getByRole('button', { name: 'Reabrir revisión', exact: true }).click()
  const confirm = page.getByRole('dialog', { name: '¿Reabrir la revisión?' })
  await confirm.getByRole('button', { name: 'Conservar decisión', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Guardar y ver resumen', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Reabrir revisión', exact: true }).click()
  await confirm.getByRole('button', { name: 'Reabrir revisión', exact: true }).click()
  await expect(page.locator('#crop-reviewed')).not.toBeChecked()
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await expect(page.locator('tbody tr').filter({ hasText: 'DEMO-008' })).toContainText('Borrador')
})

test('A to B to A with reconfirmation still invalidates an earlier crop decision', async ({ page }) => {
  await startReview(page)
  await acceptSaved(page)
  await page.getByRole('link', { name: 'Volver a Radiografía y lado', exact: true }).click()
  await page.getByRole('button', { name: 'Seleccionar imagen B', exact: true }).click()
  await page.getByRole('button', { name: 'Seleccionar imagen A', exact: true }).click()
  await page.locator('#radiograph-confirmation').check()
  // Returning to the original form values still invalidates the earlier decision when saved.
  await expect(page.locator('.rad-draft-state')).toHaveText('Tienes cambios sin guardar.')
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Tienes cambios sin guardar' })).toBeVisible()
  await page.getByRole('button', { name: 'Seguir editando', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await expect(page.locator('tbody tr').filter({ hasText: 'DEMO-008' })).toContainText('Borrador')
  await page.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.locator('#crop-reviewed')).not.toBeChecked()
  await expect(page.getByRole('button', { name: 'Aceptar recorte de ejemplo', exact: true })).toBeVisible()
})

test('changing baseline side and returning to the original side invalidates the crop decision', async ({ page }) => {
  await startReview(page)
  await acceptSaved(page)
  await page.getByRole('link', { name: 'Volver a Radiografía y lado', exact: true }).click()
  await page.getByRole('link', { name: 'Volver a datos basales', exact: true }).click()
  await page.locator('#draft-knee-left').check()
  await page.locator('#draft-knee-right').check()
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Tienes cambios sin guardar' })).toBeVisible()
  await page.getByRole('button', { name: 'Seguir editando', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await expect(page.locator('tbody tr').filter({ hasText: 'DEMO-008' })).toContainText('Borrador')
  await page.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await expect(page.locator('#radiograph-confirmation')).not.toBeChecked()
  await page.locator('#radiograph-confirmation').check()
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.locator('#crop-reviewed')).not.toBeChecked()
})

test('pending review preserves work and cancelled logout keeps the provisional decision', async ({ page }) => {
  await startReview(page)
  await page.locator('#crop-reviewed').check()
  await page.locator('#crop-reason').selectOption('other-example')
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await page.getByRole('button', { name: 'Ver revisión DEMO-008', exact: true }).click()
  await expect(page.locator('#crop-reviewed')).toBeChecked()
  await expect(page.locator('#crop-reason')).toHaveValue('other-example')
  await page.getByRole('button', { name: 'Aceptar recorte de ejemplo', exact: true }).click()
  await page.getByRole('button', { name: 'Cerrar sesión de demostración' }).click()
  await page.getByRole('button', { name: 'Seguir editando', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Reabrir revisión', exact: true })).toBeVisible()
  expect(await page.evaluate(() => sessionStorage.getItem('kneeoai:ui-demo:v1'))).toBe('active')
})

test('an image-load error removes provisional acceptance and blocks continuation', async ({ page }) => {
  await startReview(page)
  await page.locator('#crop-reviewed').check()
  await page.getByRole('button', { name: 'Aceptar recorte de ejemplo', exact: true }).click()
  await page.locator('.crop-preview-frame image').first().dispatchEvent('error')
  await expect(page.locator('.crop-load-error')).toBeVisible()
  await expect(page.locator('#crop-reviewed')).not.toBeChecked()
  await expect(page.getByRole('button', { name: 'Aceptar recorte de ejemplo', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'Guardar y ver resumen', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Resumen del caso', exact: true })).not.toBeVisible()
})

test('saved reviews survive reload while missing sources and legacy reviews remain blocked', async ({ page }) => {
  await startReview(page)
  await acceptSaved(page)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Revisión del recorte', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Reabrir revisión', exact: true })).toBeVisible()
  await expect(page.locator('#crop-reviewed')).toHaveCount(0)
  await page.goto('/evaluaciones/no-such-case/revision')
  await expect(page.getByRole('heading', { name: 'Revisión no disponible' })).toBeVisible()
  await page.goto('/evaluaciones/demo-002/revision')
  await expect(page.getByRole('heading', { name: 'Revisión no disponible' })).toBeVisible()
  await page.goto('/evaluaciones/demo-005/revision')
  await expect(page.getByRole('heading', { name: 'Imagen y lado pendientes' })).toBeVisible()
  await expect(page.locator('.crop-preview-frame')).toHaveCount(0)
})

