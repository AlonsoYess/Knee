import { test, expect, type Page } from '@playwright/test'

async function start(page: Page) {
  await page.goto('/acceso')
  await page.getByRole('button', { name: 'Completar datos de ejemplo' }).click()
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await page.getByRole('button', { name: 'Nueva evaluación', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Nueva evaluación', exact: true })).toBeVisible()
}

test('partial drafts preserve missing fields and edit a single stable case', async ({ page }) => {
  await start(page)
  await expect(page.locator('#draft-code')).toHaveValue('DEMO-008')
  await page.screenshot({ path: 'test-results/new-evaluation-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(8)
  const row = page.locator('tbody tr').filter({ hasText: 'DEMO-008' })
  await expect(row).toContainText('Rodilla pendiente')
  await row.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await expect(page.locator('#draft-age')).toBeEmpty()
  await expect(page.locator('#draft-sex')).toHaveValue('')
  await expect(page.locator('#draft-bmi')).toBeEmpty()
  await expect(page.locator('#draft-knee-left')).not.toBeChecked()
  await page.getByRole('button', { name: 'Completar ejemplo', exact: true }).click()
  await page.locator('#draft-age').fill('63')
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(8)
  await expect(page.locator('tbody tr').filter({ hasText: 'DEMO-008' })).toHaveCount(1)
  await page.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await expect(page.locator('#draft-age')).toHaveValue('63')
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  await page.getByRole('button', { name: 'Nueva evaluación', exact: true }).click()
  await expect(page.locator('#draft-code')).toHaveValue('DEMO-009')
})

test('validation, decimal comma and repeat continue never create predictions or duplicates', async ({ page, baseURL }) => {
  const localOrigin = new URL(baseURL!).origin
  const errors: string[] = []
  const externalRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (!request.url().startsWith(`${localOrigin}/`) && !request.url().startsWith('data:')) externalRequests.push(request.url())
  })
  await start(page)
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.locator('#draft-age')).toBeFocused()
  await expect(page.locator('#draft-age-error')).toBeVisible()
  await expect(page.locator('#draft-sex-error')).toBeVisible()
  await expect(page.locator('#draft-bmi-error')).toBeVisible()
  await expect(page.locator('#draft-knee-error')).toBeVisible()
  await page.locator('#draft-age').fill('62.5')
  await page.locator('#draft-bmi').fill('-2')
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await expect(page.locator('#draft-age-error')).toContainText('entera')
  await expect(page.locator('#draft-bmi-error')).toContainText('mayor que cero')
  await page.getByRole('button', { name: 'Completar ejemplo', exact: true }).click()
  // Completing an example must preserve values the user already entered, including errors to correct.
  await expect(page.locator('#draft-age')).toHaveValue('62.5')
  await expect(page.locator('#draft-bmi')).toHaveValue('-2')
  await page.locator('#draft-age').fill('62')
  await page.locator('#draft-bmi').fill('28,4')
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Radiografía y lado', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Volver a datos basales', exact: true }).click()
  await expect(page.locator('#draft-bmi')).toHaveValue('28.4')
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Radiografía y lado', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await expect(page.locator('tbody tr')).toHaveCount(8)
  await expect(page.locator('tbody tr').filter({ hasText: 'DEMO-008' })).toContainText('Borrador')
  expect(errors).toEqual([])
  expect(externalRequests).toEqual([])
})

test('unsaved navigation and logout can be cancelled without losing the draft or demo session', async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: 'Completar ejemplo', exact: true }).click()
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Tienes cambios sin guardar' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.locator('#draft-age')).toHaveValue('62')
  await page.getByRole('button', { name: 'Cerrar sesión de demostración' }).click()
  await page.getByRole('button', { name: 'Seguir editando', exact: true }).click()
  await expect(page).toHaveURL(/\/evaluaciones\/nueva$/)
  expect(await page.evaluate(() => sessionStorage.getItem('kneeoai:ui-demo:v1'))).toBe('active')
  await page.getByRole('button', { name: 'Cerrar sesión de demostración' }).click()
  await page.getByRole('button', { name: 'Salir sin guardar', exact: true }).click()
  await expect(page).toHaveURL(/\/acceso$/)
  expect(await page.evaluate(() => sessionStorage.getItem('kneeoai:ui-demo:v1'))).toBeNull()
  await page.getByRole('button', { name: 'Completar datos de ejemplo' }).click()
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(7)
})

test('cleared drafts survive reload while unsaved fields and invalid edit routes stay distinct', async ({ page }) => {
  await start(page)
  await page.getByRole('button', { name: 'Completar ejemplo', exact: true }).click()
  await page.getByRole('button', { name: 'Limpiar campos', exact: true }).click()
  const clear = page.getByRole('dialog', { name: '¿Limpiar los campos?' })
  await clear.getByRole('button', { name: 'Seguir editando', exact: true }).click()
  await expect(page.locator('#draft-age')).toHaveValue('62')
  await page.getByRole('button', { name: 'Limpiar campos', exact: true }).click()
  await clear.getByRole('button', { name: 'Limpiar campos', exact: true }).click()
  await expect(page.locator('#draft-age')).toBeEmpty()
  await expect(page.locator('#draft-code')).toHaveValue('DEMO-008')
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await page.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await page.locator('#draft-age').fill('70')
  page.once('dialog', dialog => dialog.accept())
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Editar borrador', exact: true })).toBeVisible()
  await expect(page.locator('#draft-code')).toHaveValue('DEMO-008')
  await expect(page.locator('#draft-age')).toBeEmpty()
  await expect(page.locator('#draft-sex')).toHaveValue('')
  await expect(page.locator('#draft-bmi')).toBeEmpty()
  await page.getByRole('button', { name: 'Cerrar sesión de demostración' }).click()
  await expect(page).toHaveURL(/\/acceso$/)
  await page.getByRole('button', { name: 'Completar datos de ejemplo' }).click()
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(8)
  await page.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await expect(page.locator('#draft-age')).toBeEmpty()
  await page.goto('/evaluaciones/no-such-case/editar')
  await expect(page.getByRole('heading', { name: 'Borrador no disponible' })).toBeVisible()
  await page.goto('/evaluaciones/demo-002/editar')
  await expect(page.getByRole('heading', { name: 'Borrador no disponible' })).toBeVisible()
  await expect(page.locator('#draft-age')).toHaveCount(0)
})

test('new evaluation remains usable on mobile and preserves the form on cancelled back navigation', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await start(page)
  await page.screenshot({ path: 'test-results/new-evaluation-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Completar ejemplo', exact: true }).click()
  await page.goBack()
  await expect(page.getByRole('dialog', { name: 'Tienes cambios sin guardar' })).toBeVisible()
  await page.getByRole('button', { name: 'Seguir editando', exact: true }).click()
  await expect(page.locator('#draft-age')).toHaveValue('62')
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Radiografía y lado', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.setViewportSize({ width: 320, height: 740 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
