import { test, expect, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/acceso')
  await page.getByRole('button', { name: 'Completar datos de ejemplo' }).click()
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await expect(page).toHaveURL(/\/evaluaciones$/)
}

test('access guards, validation, password visibility, recovery and keyboard login', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/evaluaciones')
  await expect(page).toHaveURL(/\/acceso$/)
  await page.screenshot({ path: 'test-results/access-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await expect(page.getByText('Escribe tu correo de acceso.', { exact: true })).toBeVisible()
  await page.getByLabel('Correo de acceso', { exact: true }).fill('correo-invalido')
  await expect(page.getByText('Escribe tu correo de acceso.', { exact: true })).toHaveCount(0)
  await expect(page.locator('#login-email')).not.toHaveAttribute('aria-invalid', 'true')
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await expect(page.getByText('Revisa el formato del correo.')).toBeVisible()
  await page.getByRole('button', { name: 'Completar datos de ejemplo' }).click()
  await page.getByRole('button', { name: 'Mostrar contraseña' }).click()
  await expect(page.locator('#login-password')).toHaveAttribute('type', 'text')
  await page.getByRole('button', { name: 'Ocultar contraseña' }).click()
  await expect(page.locator('#login-password')).toHaveAttribute('type', 'password')
  await page.getByRole('button', { name: '¿Necesitas recuperar tu acceso?' }).click()
  await expect(page.getByRole('dialog', { name: 'Recuperar tu acceso' })).toBeVisible()
  // A click inside dialog padding must not be mistaken for its backdrop.
  await page.getByRole('dialog', { name: 'Recuperar tu acceso' }).click({ position: { x: 8, y: 8 } })
  await expect(page.getByRole('dialog', { name: 'Recuperar tu acceso' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '¿Necesitas recuperar tu acceso?' })).toBeFocused()
  await page.locator('#login-password').fill('contraseña-incorrecta')
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await expect(page.getByRole('alert')).toContainText('Los datos no corresponden')
  await page.getByRole('button', { name: 'Completar datos de ejemplo' }).click()
  await page.locator('#login-password').press('Enter')
  await expect(page.getByRole('heading', { name: 'Mis evaluaciones', exact: true })).toBeVisible()
  expect(await page.evaluate(() => JSON.stringify(sessionStorage))).not.toContain('DemoKnee2026!')
  await page.reload()
  await expect(page).toHaveURL(/\/evaluaciones$/)
  await page.getByRole('button', { name: 'Cerrar sesión de demostración' }).click()
  await expect(page).toHaveURL(/\/acceso$/)
  await page.goto('/evaluaciones')
  await expect(page).toHaveURL(/\/acceso$/)
  expect(errors).toEqual([])
})

test('list search, combined filters, empty state, case details and next-step boundary', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await login(page)
  await expect(page.locator('tbody tr')).toHaveCount(7)
  await page.screenshot({ path: 'test-results/evaluations-desktop.png', fullPage: true })
  await page.getByLabel('Estado', { exact: true }).selectOption('review')
  await expect(page.locator('tbody tr')).toHaveCount(2)
  await page.getByLabel('Buscar evaluación', { exact: true }).fill('demo-002')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  const open = page.getByRole('button', { name: 'Ver detalle de DEMO-002', exact: true })
  await open.click()
  await expect(page.getByRole('dialog')).toContainText('DEMO-002')
  await expect(page.getByRole('dialog')).toContainText('58 años')
  await page.keyboard.press('Escape')
  await expect(open).toBeFocused()
  await expect(page.getByLabel('Buscar evaluación', { exact: true })).toHaveValue('demo-002')
  await page.getByRole('link', { name: 'Ver resumen del caso DEMO-002', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Mis evaluaciones', exact: true })).toHaveClass(/section-active/)
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  await expect(page.getByLabel('Buscar evaluación', { exact: true })).toHaveValue('demo-002')
  await expect(page.getByLabel('Estado', { exact: true })).toHaveValue('review')
  await expect(page.locator('tbody tr')).toHaveCount(1)
  await page.getByLabel('Buscar evaluación', { exact: true }).fill('sin-coincidencias')
  await expect(page.getByRole('heading', { name: 'No encontramos evaluaciones' })).toBeVisible()
  await page.getByRole('button', { name: 'Mostrar todas las evaluaciones' }).click()
  await expect(page.locator('tbody tr')).toHaveCount(7)
  await page.getByRole('button', { name: 'Nueva evaluación', exact: true }).click()
  await expect(page).toHaveURL(/\/evaluaciones\/nueva$/)
  await expect(page.getByRole('heading', { name: 'Nueva evaluación', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Mis evaluaciones', exact: true })).toHaveClass(/section-active/)
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  await page.getByRole('button', { name: 'Ayuda y alcance' }).click()
  await expect(page.getByRole('dialog')).toContainText('48 meses')
  await page.keyboard.press('Escape')
  expect(errors).toEqual([])
})

test('mobile access and evaluation actions fit the viewport', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/acceso')
  await page.screenshot({ path: 'test-results/access-mobile.png', fullPage: true })
  await login(page)
  await expect(page.getByRole('button', { name: 'Retomar DEMO-001', exact: true })).toBeVisible()
  await page.screenshot({ path: 'test-results/evaluations-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Ver detalle de DEMO-004', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('Imagen no utilizable')
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 320, height: 740 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
