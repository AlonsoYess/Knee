test('partial image drafts and removal are reversible until saved', async ({ page }) => {
  await startImage(page)
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await page.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await expect(page.locator('.rad-empty-preview')).toBeVisible()
  await page.getByRole('button', { name: 'Seleccionar imagen A', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await page.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await expect(page.locator('#radiograph-confirmation')).not.toBeChecked()
  await page.getByRole('button', { name: 'Quitar imagen', exact: true }).click()
  const remove = page.getByRole('dialog', { name: '¿Quitar la imagen seleccionada?', exact: true })
  await remove.getByRole('button', { name: 'Seguir editando', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Seleccionar imagen A', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Quitar imagen', exact: true }).click()
  await remove.getByRole('button', { name: 'Quitar imagen', exact: true }).click()
  await expect(page.locator('.rad-empty-preview')).toBeVisible()
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  await page.getByRole('button', { name: 'Salir sin guardar', exact: true }).click()
  await page.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Seleccionar imagen A', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('saved images survive reload while missing baselines and invalid routes remain blocked', async ({ page }) => {
  await startImage(page)
  await page.getByRole('button', { name: 'Seleccionar imagen A', exact: true }).click()
  await page.locator('#radiograph-confirmation').check()
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await page.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  const imageUrl = page.url()
  await page.getByRole('button', { name: 'Seleccionar imagen B', exact: true }).click()
  page.once('dialog', dialog => dialog.accept())
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Radiografía y lado', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Seleccionar imagen A', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#radiograph-confirmation')).toBeChecked()
  await page.goto('/evaluaciones/no-such-case/radiografia')
  await expect(page.getByRole('heading', { name: 'Borrador no disponible' })).toBeVisible()
  await page.goto('/evaluaciones/demo-002/radiografia')
  await expect(page.getByRole('heading', { name: 'Borrador no disponible' })).toBeVisible()
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  await page.getByRole('button', { name: 'Nueva evaluación', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar y salir', exact: true }).click()
  await page.getByRole('button', { name: 'Retomar DEMO-009', exact: true }).click()
  const partialUrl = page.url().replace(/\/editar$/, '/radiografia')
  await page.goto(partialUrl)
  await expect(page.getByRole('heading', { name: 'Datos basales pendientes' })).toBeVisible()
  expect(imageUrl).toContain('/radiografia')
  await expect(page.getByRole('button', { name: 'Seleccionar imagen A', exact: true })).toHaveCount(0)
})

