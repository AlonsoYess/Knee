import { test, expect, type Page } from '@playwright/test'

async function startImage(page: Page) {
  await page.goto('/acceso')
  await page.getByRole('button', { name: 'Completar datos de ejemplo' }).click()
  await page.getByRole('button', { name: 'Entrar a la demostración' }).click()
  await page.getByRole('button', { name: 'Nueva evaluación', exact: true }).click()
  await page.getByRole('button', { name: 'Completar ejemplo', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Radiografía y lado', exact: true })).toBeVisible()
}

test('image selection, enlargement and confirmed side persist as a preparation draft', async ({ page, baseURL }) => {
  const localOrigin = new URL(baseURL!).origin
  const errors: string[] = []
  const external: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (!request.url().startsWith(`${localOrigin}/`) && !request.url().startsWith('data:')) external.push(request.url()) })
  await startImage(page)
  await expect(page.locator('input[type="file"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.locator('#radiograph-sample-error')).toBeVisible()
  await expect(page.locator('#radiograph-confirmation')).toBeDisabled()
  const choose = page.getByRole('button', { name: 'Seleccionar imagen A', exact: true })
  await choose.click()
  await expect(choose).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.rad-preview img')).toHaveJSProperty('naturalWidth', 960)
  await page.getByRole('button', { name: 'Ampliar imagen', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Vista ampliada de la imagen' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Ampliar imagen', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.locator('#radiograph-confirmation-error')).toBeVisible()
  await page.locator('#radiograph-confirmation').check()
  await page.screenshot({ path: 'test-results/radiograph-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Revisión del recorte', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Mis evaluaciones', exact: true }).click()
  const row = page.locator('tbody tr').filter({ hasText: 'DEMO-008' })
  await expect(row).toContainText('Borrador')
  await expect(row).toContainText('Radiografía y lado')
  await row.getByRole('button', { name: 'Retomar DEMO-008', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Radiografía y lado', exact: true })).toBeVisible()
  await expect(choose).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#radiograph-confirmation')).toBeChecked()
  expect(errors).toEqual([])
  expect(external).toEqual([])
})

test('changing image or side invalidates confirmation and a mismatch cannot continue', async ({ page }) => {
  await startImage(page)
  await page.getByRole('button', { name: 'Seleccionar imagen A', exact: true }).click()
  await page.locator('#radiograph-confirmation').check()
  await page.getByRole('button', { name: 'Seleccionar imagen B', exact: true }).click()
  await expect(page.locator('#radiograph-confirmation')).not.toBeChecked()
  await page.locator('#radiograph-confirmation').check()
  await page.getByRole('button', { name: 'Seleccionar imagen A', exact: true }).click()
  await expect(page.locator('#radiograph-confirmation')).not.toBeChecked()
  await page.locator('#radiograph-confirmation').check()
  await page.locator('#radiograph-side-left').check()
  await expect(page.locator('#radiograph-confirmation')).not.toBeChecked()
  await expect(page.locator('#radiograph-confirmation')).toBeDisabled()
  await expect(page.locator('#radiograph-side-error')).toContainText('no coincide')
  await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Revisión del recorte', exact: true })).not.toBeVisible()
  await expect(page.locator('#radiograph-side-error')).toBeVisible()
  await page.locator('#radiograph-side-right').check()
  await expect(page.locator('#radiograph-confirmation')).not.toBeChecked()
  await expect(page.locator('#radiograph-confirmation')).toBeEnabled()
})

test('a slow image cannot be confirmed or enlarged before it has loaded', async ({ page }) => {
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/demo/radiografia-demo-a.svg', async route => {
    await gate
    await route.continue()
  })
  try {
    await startImage(page)
    await page.getByRole('button', { name: 'Seleccionar imagen A', exact: true }).click()
    await expect(page.getByText('Cargando la imagen. Espera a verla para confirmar el lado y continuar.')).toBeVisible()
    await expect(page.locator('#radiograph-confirmation')).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Ampliar imagen', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Guardar y continuar', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Guardar y salir', exact: true })).toBeEnabled()
    release()
    await expect(page.locator('#radiograph-confirmation')).toBeEnabled()
    await page.locator('#radiograph-confirmation').check()
    await page.getByRole('button', { name: 'Guardar y continuar', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Revisión del recorte', exact: true })).toBeVisible()
  } finally { release() }
})

